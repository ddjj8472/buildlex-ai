export function expandTerms(text: string): string[] {
  const out = new Set<string>();
  for (const [re, terms] of SYNONYMS) if (re.test(text)) terms.forEach(t => out.add(t));
  return [...out];
}

export function hintLaws(text: string): string[] {
  const out = new Set<string>();
  for (const h of LAW_HINTS) if (h.pattern.test(text)) h.laws.forEach(l => out.add(l));
  return [...out];
}
